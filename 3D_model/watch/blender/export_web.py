"""Export the watch for the web viewer: ../web/watch.glb and ../web/watch.glb.js.

  blender -b watch.blend -P export_web.py

Uses the blender-export-pipelines skill script (plain GLB, no compression: the file is small).
Custom properties are exported as glTF extras, so every part keeps its explode_mm vector.
watch.glb.js holds the same file as base64 in window.WATCH_GLB_BASE64, because a page
opened by double-click (file://) cannot fetch a local .glb.
"""
import base64
import json
import os
import sys

import bpy

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, "C:/maven/Hackathon_map/rendering/blender-skills/skills/blender-export-pipelines/scripts")
import export_asset  # noqa: E402
import watch_lib     # noqa: E402


def main():
    watch_lib.set_explode(0.0)
    web = os.path.abspath(os.path.join(HERE, "..", "web"))
    os.makedirs(web, exist_ok=True)
    glb = os.path.join(web, "watch.glb")
    result = export_asset.run(preset="gltf", collection="WATCH", out=glb,
                              set=["export_extras=True", "export_cameras=False", "export_lights=False"])
    with open(glb, "rb") as f:
        data = f.read()
    with open(glb + ".js", "w", encoding="ascii", newline="\n") as f:
        f.write("// Generated by blender/export_web.py. watch.glb as base64.\n")
        f.write('window.WATCH_GLB_BASE64 = "' + base64.b64encode(data).decode("ascii") + '";\n')
    print("@@JSON@@" + json.dumps({"glb_kb": round(len(data) / 1024), "result": result}, default=str))


if __name__ == "__main__":
    main()
